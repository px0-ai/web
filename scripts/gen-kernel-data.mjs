// Regenerates src/data/kernel.ts, the Linux kernel facts behind the hero demo.
// Usage: node scripts/gen-kernel-data.mjs [path/to/linux]   (default: ../px0/bench-repos/linux)
// See docs/hero-kernel-demo.md.

import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const WEB = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const LINUX = resolve(process.argv[2] || resolve(WEB, '../px0/bench-repos/linux'));
const OUT = resolve(WEB, 'src/data/kernel.ts');

// ── knobs: change these, then update the matching constants in Hero.astro ──
const FILE = 'lib/sort.c';            // the file the demo opens
const START = 225;                    // excerpt window, inclusive
const END = 260;
const SYMBOL = 'do_swap';             // hovered symbol whose references the inspector lists
const WINDOW = 14;                    // tree rows shown above and below FILE
const PATH_GLOBS = [                  // palette sample: every file directly in these directories
  '*', 'kernel/*', 'kernel/sched/*', 'lib/*', 'mm/*', 'init/*', 'fs/*', 'fs/ext4/*',
  'block/*', 'io_uring/*', 'arch/x86/kernel/*', 'ipc/*',
];
const EXTRA_PATHS = [                 // plus a few well-known headers
  'sched', 'sort', 'list', 'list_sort', 'mm', 'fs', 'slab', 'kernel', 'types', 'rbtree', 'spinlock',
  'mutex', 'rcupdate', 'workqueue', 'syscalls', 'printk', 'module', 'init', 'bpf', 'io_uring',
].map((h) => `include/linux/${h}.h`);

const git = (...args) => execFileSync('git', ['-C', LINUX, ...args], { encoding: 'utf8', maxBuffer: 64 << 20 });
const lines = (s) => s.split('\n').filter(Boolean);
const fail = (msg) => {
  console.error(`gen-kernel-data: ${msg}`);
  process.exit(1);
};

const commit = git('rev-parse', '--short=12', 'HEAD').trim();

// Palette sample: tracked paths only, so build artefacts never leak in.
const paths = [...new Set(lines(git('ls-files', '--', ...PATH_GLOBS.map((g) => `:(glob)${g}`), ...EXTRA_PATHS)))].sort();
if (!paths.includes(FILE)) fail(`${FILE} is not in the palette sample; widen PATH_GLOBS`);
if (paths.some((p) => /['\\]/.test(p))) fail('a path needs escaping');

// Tracked entries of one directory, as [name, isDir].
const entries = (dir) =>
  lines(git('ls-tree', 'HEAD', dir ? `${dir}/` : '.')).map((row) => {
    const [meta, path] = row.split('\t');
    return [path.slice(dir ? dir.length + 1 : 0), meta.split(' ')[1] === 'tree'];
  });

// Root, as the px0 tree lists it: directories first, then files, case-insensitive.
const byName = (a, b) => a.toLowerCase().localeCompare(b.toLowerCase(), 'en');
const root = entries('');
const rootDirs = root.filter(([, d]) => d).map(([n]) => n).sort(byName);
const rootFiles = root.filter(([, d]) => !d).map(([n]) => n).sort(byName);

// The tree scrolled to FILE: its siblings in byte order, directories suffixed with '/'.
const parent = dirname(FILE);
const base = FILE.slice(parent.length + 1);
const siblings = entries(parent).map(([n, d]) => (d ? `${n}/` : n)).sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
const at = siblings.indexOf(base);
if (at < 0) fail(`${base} not found in ${parent}/`);
const libWindow = siblings.slice(Math.max(0, at - WINDOW), at + WINDOW + 1);

// The file itself.
const src = readFileSync(resolve(LINUX, FILE), 'utf8').split('\n');
if (src.at(-1) === '') src.pop();
if (END > src.length) fail(`END ${END} is past the end of ${FILE} (${src.length} lines)`);
const excerpt = src.slice(START - 1, END);

// Top-level function definitions: a return type and a name at column 0, followed by '('.
const symbols = [];
src.forEach((l, i) => {
  const m = /^(?!typedef\b|return\b|#)[A-Za-z_][\w \t*]*?[\s*](\w+)\(/.exec(l);
  if (m) symbols.push({ name: m[1], kind: 'func', line: i + 1 });
});
if (!symbols.some((s) => s.name === SYMBOL)) fail(`no definition of ${SYMBOL} in ${FILE}`);

// Every mention of SYMBOL; the definition goes first.
const def = symbols.find((s) => s.name === SYMBOL).line;
const refs = [];
src.forEach((l, i) => {
  if (new RegExp(`\\b${SYMBOL}\\(`).test(l)) refs.push({ line: i + 1, text: l.trim() });
});
refs.sort((a, b) => (a.line === def ? -1 : b.line === def ? 1 : a.line - b.line));

const wrap = (items, width = 100) => {
  const out = [];
  let cur = '';
  for (const it of items) {
    const piece = `'${it}',`;
    if (cur && cur.length + piece.length + 1 > width) {
      out.push(`  ${cur}`);
      cur = piece;
    } else {
      cur = cur ? `${cur} ${piece}` : piece;
    }
  }
  if (cur) out.push(`  ${cur}`);
  return out.join('\n');
};

const ts = `// Facts about the Linux kernel tree the hero mock opens, taken from px0's bench-repos/linux (${commit}).
// Generated by scripts/gen-kernel-data.mjs; see docs/hero-kernel-demo.md. Do not edit by hand.

/** Real tracked paths: the root, plus kernel/, lib/, mm/, fs/ext4/, block/, io_uring/ and a few more. */
export const KERNEL_FILES = [
${wrap(paths)}
];

/** The workspace root as the tree lists it. */
export const ROOT_DIRS = [
${wrap(rootDirs)}
];
export const ROOT_FILES = [
${wrap(rootFiles)}
];

/** The tree scrolled to ${FILE}: the entries of ${parent}/ around it. Directories end in '/'. */
export const LIB_WINDOW = [
${wrap(libWindow)}
];

/** Top-level functions in ${FILE}. */
export const SORT_SYMBOLS = [
${symbols.map((s) => `  { name: '${s.name}', kind: '${s.kind}', line: ${s.line} },`).join('\n')}
];

/** Every mention of ${SYMBOL} in ${FILE}. The first is its definition. */
export const DO_SWAP_REFS = [
${refs.map((r) => `  { line: ${r.line}, text: ${JSON.stringify(r.text)} },`).join('\n')}
];

/** ${FILE}, lines ${START} to ${END}, verbatim. */
export const SORT_EXCERPT = {
  file: '${FILE}',
  total: ${src.length},
  start: ${START},
  lines: [
${excerpt.map((l) => `    ${JSON.stringify(l)},`).join('\n')}
  ],
};
`;

writeFileSync(OUT, ts);
console.log(`wrote ${OUT}`);
console.log(`  linux ${commit}: ${paths.length} palette paths, ${rootDirs.length} root dirs, ${rootFiles.length} root files`);
console.log(`  ${FILE}: ${src.length} lines, excerpt ${START}-${END}, ${symbols.length} functions, ${refs.length} mentions of ${SYMBOL}`);
